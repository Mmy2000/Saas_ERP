#!/usr/bin/env bash
# Step 2, as root, after bootstrap.sh: secrets, database, Python, Chromium, the services, the
# certificate and nginx, then a first backup. Safe to run again: it keeps the .env, the
# database roles and the certificate it finds, and re-applies everything else.
#
#   sudo bash /srv/gweb/deploy/install.sh        (reads /etc/gweb/deploy.conf)
set -euo pipefail

CONF=/etc/gweb/deploy.conf
CF_INI=/etc/letsencrypt/cloudflare.ini
die() { echo "ERROR: $*" >&2; exit 1; }
step() { echo; echo "== $*"; }

[[ $EUID -eq 0 ]] || die "Run as root (sudo)."
[[ -f $CONF ]] || die "$CONF is missing (copy deploy/deploy.conf.example)."
# shellcheck source=/dev/null
source "$CONF"
[[ -n ${DOMAIN:-} && $DOMAIN != example.com ]] || die "Set DOMAIN in $CONF."
[[ -n ${ADMIN_EMAIL:-} && $ADMIN_EMAIL != you@example.com ]] || die "Set ADMIN_EMAIL in $CONF."
[[ -d $APP_DIR/.git ]] || die "$APP_DIR has no code: run bootstrap.sh first."

ENV_FILE=$APP_DIR/.env
DEPLOY=$APP_DIR/deploy
WORKERS=${WEB_WORKERS:-$(( $(nproc) * 2 + 1 ))}
as_app() { sudo -u "$APP_USER" -H "$@"; }
cd "$APP_DIR"

step "Folders (nginx may read the code and static files only)"
usermod -aG "$APP_USER" www-data
chmod 750 "$APP_DIR"
install -d -o "$APP_USER" -g "$APP_USER" -m 750 var var/static
for private in var/media var/backups var/cache var/home var/wa-sessions var/ms-playwright; do
    install -d -o "$APP_USER" -g "$APP_USER" -m 700 "$private"
done

step "Python 3.13 environment"
[[ -x venv/bin/python ]] || as_app python3.13 -m venv venv
as_app venv/bin/pip install --quiet --upgrade pip
as_app venv/bin/pip install --quiet -r requirements/base.txt

step "Secrets and settings ($ENV_FILE)"
if [[ ! -f $ENV_FILE ]]; then
    token() { python3 -c 'import secrets; print(secrets.token_hex(32))'; }
    fernet=$(as_app venv/bin/python -c \
        'from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())')
    owner_pw=$(token); rw_pw=$(token); platform_pw=$(token)
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by deploy/install.sh on $(date -u +%F). Read by systemd (EnvironmentFile) and by
# Django. Every setting is explained in .env.example. No comments after values: systemd keeps
# them as part of the value.
DJANGO_SETTINGS_MODULE=config.settings.prod
DJANGO_DEBUG=false
DJANGO_SECRET_KEY=$(token)
DJANGO_ALLOWED_HOSTS=.$DOMAIN
TENANT_BASE_DOMAIN=$DOMAIN
PLATFORM_HOSTS=admin.$DOMAIN
SITE_SCHEME=https
SITE_PORT=

DATABASE_URL=postgres://app_rw:$rw_pw@127.0.0.1:5432/gweb
DATABASE_OWNER_URL=postgres://app_owner:$owner_pw@127.0.0.1:5432/gweb
BACKUP_DATABASE_URL=postgres://app_platform:$platform_pw@127.0.0.1:5432/gweb
DB_CONN_MAX_AGE=60

# KEEP A COPY OF THESE TWO OUTSIDE THE SERVER (password manager): they are not in the backups,
# and without them customers' national IDs can never be read again.
FIELD_ENCRYPTION_KEY=$fernet
BLIND_INDEX_KEY=$(token)

# E-mail (documents, reminders, error alerts). Fill in, then: systemctl restart gweb-web gweb-worker
# EMAIL_URL=smtp+tls://user:password@smtp.example.com:587
DEFAULT_FROM_EMAIL=no-reply@$DOMAIN
ERROR_ALERT_EMAILS=$ADMIN_EMAIL

PLAYWRIGHT_BROWSERS_PATH=$APP_DIR/var/ms-playwright

# Gweb's hosted WhatsApp gateway and an SMS provider for one-time codes (optional):
# WHATSAPP_GATEWAY_URL=
# WHATSAPP_GATEWAY_KEY=
# SMS_API_URL=
# SMS_API_KEY=
# SMS_SENDER=
EOF
    if [[ ${WA_GATEWAY:-no} == yes ]]; then
        cat >> "$ENV_FILE" <<EOF

# The shops' own WhatsApp numbers (ops/wa-gateway on this server).
WA_GATEWAY_URL=http://127.0.0.1:3002
WA_GATEWAY_KEY=$(token)
EOF
    fi
    umask 022
    chown "$APP_USER:$APP_USER" "$ENV_FILE"
    chmod 600 "$ENV_FILE"
    echo "Created. Copy FIELD_ENCRYPTION_KEY and BLIND_INDEX_KEY to your password manager now."
else
    echo "Kept the existing one."
fi
setting() { sed -n "s/^$1=//p" "$ENV_FILE" | head -1; }
password_in() { setting "$1" | sed -E 's|^postgres://[^:]+:([^@]+)@.*|\1|'; }

step "PostgreSQL: the three roles and the database (ops/db/bootstrap.sql)"
systemctl enable --now --quiet postgresql
if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname = 'app_owner'" | grep -q 1; then
    echo "The roles exist: kept."
else
    # Root reads the file and pipes it in: the postgres user can't read the app folder.
    # shellcheck disable=SC2024
    sudo -u postgres psql -q -v ON_ERROR_STOP=1 -v dbname=gweb \
        -v owner_pw="$(password_in DATABASE_OWNER_URL)" -v rw_pw="$(password_in DATABASE_URL)" \
        -v platform_pw="$(password_in BACKUP_DATABASE_URL)" < "$APP_DIR/ops/db/bootstrap.sql"
fi

step "The manage.py wrapper (gweb-manage)"
install -m 755 "$DEPLOY/gweb-manage" /usr/local/bin/gweb-manage

step "Schema and static files"
gweb-manage migrate --database owner --noinput
gweb-manage collectstatic --noinput -v 0

step "Chromium for the PDFs"
venv/bin/python -m playwright install-deps chromium >/dev/null
as_app env PLAYWRIGHT_BROWSERS_PATH="$APP_DIR/var/ms-playwright" \
    venv/bin/python -m playwright install chromium

if [[ ${WA_GATEWAY:-no} == yes ]]; then
    step "WhatsApp gateway (Node packages)"
    (cd ops/wa-gateway && as_app npm ci --omit=dev --no-audit --no-fund --silent)
fi

step "Services and timers (systemd)"
render() {
    sed -e "s|@APP_DIR@|$APP_DIR|g" -e "s|@APP_USER@|$APP_USER|g" -e "s|@WORKERS@|$WORKERS|g" \
        -e "s|@DOMAIN@|$DOMAIN|g" "$1"
}
for unit in "$DEPLOY"/systemd/*.service "$DEPLOY"/systemd/*.timer; do
    render "$unit" > "/etc/systemd/system/$(basename "$unit")"
done
systemctl daemon-reload
services=(gweb-web gweb-worker gweb-monitor)
[[ ${WA_GATEWAY:-no} == yes ]] && services+=(gweb-wa-gateway)
systemctl enable --quiet "${services[@]}" gweb-prune-traffic.timer
systemctl restart "${services[@]}"
systemctl start gweb-prune-traffic.timer
if [[ -n ${OFFSITE_REMOTE:-} ]] && as_app rclone listremotes 2>/dev/null | grep -qx "$OFFSITE_REMOTE"; then
    systemctl enable --now --quiet gweb-offsite.timer
    echo "Off-site copies: on ($OFFSITE_REMOTE)."
else
    echo "Off-site copies: OFF (no rclone remote '${OFFSITE_REMOTE:-}' for $APP_USER yet)."
fi

step "TLS certificate for $DOMAIN and *.$DOMAIN (Let's Encrypt, Cloudflare DNS)"
if [[ -f /etc/letsencrypt/live/$DOMAIN/fullchain.pem ]]; then
    echo "The certificate exists: kept (certbot.timer renews it)."
else
    [[ -f $CF_INI ]] || die "$CF_INI is missing: put your Cloudflare API token in it (see docs/operations/deploy.md), then run this again."
    chmod 600 "$CF_INI"
    certbot certonly --non-interactive --agree-tos -m "$ADMIN_EMAIL" \
        --dns-cloudflare --dns-cloudflare-credentials "$CF_INI" \
        --dns-cloudflare-propagation-seconds 30 \
        -d "$DOMAIN" -d "*.$DOMAIN" --deploy-hook "systemctl reload nginx"
fi

step "nginx"
systemctl enable --now --quiet nginx
install -d -m 755 /var/www/letsencrypt
render "$DEPLOY/nginx/gweb.conf" > /etc/nginx/sites-available/gweb
ln -sf /etc/nginx/sites-available/gweb /etc/nginx/sites-enabled/gweb
rm -f /etc/nginx/sites-enabled/default
nginx -t -q
systemctl reload nginx

step "A first backup"
gweb-manage backup

step "Ready?"
for _ in $(seq 1 30); do
    if curl -fs --resolve "admin.$DOMAIN:443:127.0.0.1" "https://admin.$DOMAIN/readyz/" \
        -o /dev/null; then
        echo "https://admin.$DOMAIN/readyz/ answers ok."
        break
    fi
    sleep 3
done
curl -sS --resolve "admin.$DOMAIN:443:127.0.0.1" "https://admin.$DOMAIN/readyz/" || true
echo
echo "Next: gweb-manage createsuperuser   (your staff account for https://admin.$DOMAIN/)"
